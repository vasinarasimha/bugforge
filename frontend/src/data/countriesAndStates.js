export const getCountries = () => countriesData.map((c) => ({
  name: c.name,
  code: c.code,
  dialCode: c.dialCode,
  flag: c.flag,
}))

export const getStatesByCountry = (countryCodeOrName) => {
  if (!countryCodeOrName) return []
  const country = countriesData.find(
    (c) =>
      c.code.toLowerCase() === countryCodeOrName.toLowerCase() ||
      c.name.toLowerCase() === countryCodeOrName.toLowerCase(),
  )
  return country ? country.states : []
}

export const getCountryByCodeOrName = (codeOrName) => {
  if (!codeOrName) return null
  return countriesData.find(
    (c) =>
      c.code.toLowerCase() === codeOrName.toLowerCase() ||
      c.name.toLowerCase() === codeOrName.toLowerCase(),
  ) || null
}

export const getDialCodes = () => countriesData.map((c) => ({
  name: c.name,
  code: c.code,
  dialCode: c.dialCode,
  flag: c.flag,
}))
